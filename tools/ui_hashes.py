# Writes runtime/src/core/tlg/ui_textures.h: the texture-pack hash (XXH3 of the pixel data, as the
# runtime computes it for a texture loaded as is) of every copy, in every language archive, of the
# game's menu textures the Options rows need to recognise.
import os, sys, xxhash
sys.path.insert(0, os.path.dirname(__file__))
from psarc import Psarc

GAME = "D:/Games/CUSA03627"
ARCHIVES = ["trico_boot", "trico_enu", "trico_esl", "trico_frc", "trico_ptb"]
# Tag name -> file stem. Tags are bit numbers of a per-frame mask.
TAGS = {
    "OptionTitle": "sys_option_title_1",
    "ItemCamera": "sys_option_item_cam_1",
    "ItemScreen": "sys_option_item_screen_1",
    "ItemAudio": "sys_option_item_audio_1",
    "ItemCopyright": "sys_option_item_copyright_1",
    "ItemBack": "sys_option_item_return_1",
    "Cursor": "sys_cursor",
    "CameraTitle": "sys_option_item_cam_title_1",
    "ScreenTitle": "sys_option_item_screen_title_1",
    "AudioTitle": "sys_option_item_audio_title_1",
    "CopyrightTitle": "sys_option_item_copyright_title_1",
    "GuideTitle": "sys_option_item_guide_title_1",
    "ItemGuide": "sys_option_item_guide_1",
    "ItemTreasure": "sys_option_item_treasure_1",
    "PauseTitle": "sys_pause_title_1",
    "ControllerBase": "guide_controller_base_bc7",
}

found = {t: set() for t in TAGS}
for a in ARCHIVES:
    p = Psarc(f"{GAME}/{a}.psarc")
    for i, name in enumerate(p.names[1:], 1):
        if not name.endswith(".gnf"):
            continue
        stem = name.rsplit("/", 1)[-1][:-4]
        for tag, want in TAGS.items():
            if stem == want:
                found[tag].add((xxhash.xxh3_64_intdigest(p.read(i)[256:]), f"{a}:{name}"))

out = ["// Generated by tools/ui_hashes.py from the game's archives. Do not edit.",
       "#pragma once", "", "#include \"common/types.h\"", "", "namespace Tlg::Ui {", "",
       "enum Tag : u32 {"]
out += [f"    {t} = {i}," for i, t in enumerate(TAGS)]
out += ["    TagCount,", "};", "", "struct TextureTag {", "    u64 hash;", "    Tag tag;", "};", "",
        "constexpr TextureTag TextureTags[] = {"]
for tag in TAGS:
    if not found[tag]:
        sys.exit(f"missing {tag}")
    seen = set()
    for h, where in sorted(found[tag]):
        if h in seen:
            continue
        seen.add(h)
        out.append(f"    {{0x{h:016x}ULL, {tag}}}, // {where}")
out += ["};", "", "} // namespace Tlg::Ui", ""]
dst = "D:/tlg-pc/runtime/src/core/tlg/ui_textures.h"
os.makedirs(os.path.dirname(dst), exist_ok=True)
open(dst, "w", newline="\n").write("\n".join(out))
print(sum(len(v) for v in found.values()), "hashes")
